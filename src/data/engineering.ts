/**
 * Engineering and research sheets (E-100 series). Facts here are declared as data, never inferred
 * from prose at runtime. Counts of figures, sections and reading time are derived by the parser.
 * Tags and the E-102 and E-103 descriptions are the author's, verbatim from the previous projects.ts.
 */
export interface MetaCell {
  label: string;
  value: string;
}

export interface ResultCell {
  value: string;
  label: string;
  note?: string;
}

export interface ChainNode {
  id: string;
  label: string;
  sub?: string;
}

export interface ChainCut {
  id: 'A' | 'B' | 'C';
  /** Node id the cut follows. */
  after: string;
  /** Figure numbers (document order) captured at this cut. */
  figures: number[];
  label: string;
}

export interface EngineeringEntry {
  sheet: string;
  slug?: string;
  title: string;
  description: string;
  tags: string[];
  /** Short headline number for the schedule row, or null. */
  keyFigure: string | null;
  status: 'issued' | 'hold';
  meta: MetaCell[];
  results?: { label: string; source?: string; cells: ResultCell[] };
  /** Cover figure: a real figure (by document-order number) or the generated diagram. */
  cover?: { kind: 'figure'; n: number; src: string } | { kind: 'diagram' };
  /** 64 x 48 row thumbnail generated by scripts/figure-meta.mjs. */
  thumb?: string;
  chain?: { nodes: ChainNode[]; cuts: ChainCut[] };
}

